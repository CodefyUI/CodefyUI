"""Enrollment and the stored worker credential, agent side (#780).

``cdui agent start --control URL --token T`` with an enrollment token
(``abcdef.0123456789abcdef``, generated by the Workers panel) trades it,
once, for a long-lived worker token: ``POST <URL>/api/workers/enroll``.
The worker token is written with the control URL and the worker name to
``<user-data>/agent/<host>-<port>.token`` (mode 0600, JSON) and presented
on every ``/ws/worker`` dial from then on, so a restarted agent reconnects
without enrolling again. ``cdui agent forget URL`` deletes that file.

Over ``https`` the file also records the control plane's certificate
fingerprint the user pinned with ``--ca-fingerprint`` (#786,
``ca_fingerprint``, SPKI sha256 of the leaf), so later starts keep pinning
it (``app.agent.trust``). Without a pin it records nothing: the system CAs
decide. A malformed stored fingerprint is reported and ignored; the worker
token stays usable.

One file per control plane (host and port), so one machine can serve two
control planes. Plain ``urllib``: the agent stays free of the server's
dependencies.

An SSH worker's agent (#784) is given ``--uds PATH`` as well: the request
goes to that Unix socket (the end of the control plane's reverse forward)
instead of a TCP connection to the URL's host, and the URL still names
the control plane (the credential file, the ``Host`` header).
"""

from __future__ import annotations

import http.client
import json
import logging
import os
import re
import socket
import ssl
import sys
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit, urlunsplit

from ..core import tls_fingerprint as fp
from .trust import ControlPlaneTrust, TrustError, untrusted_message

logger = logging.getLogger(__name__)

#: Seconds the enrollment request may take.
ENROLL_TIMEOUT_S = 30.0
CREDENTIAL_DIR_NAME = "agent"


class EnrollError(RuntimeError):
    """Enrollment failed; the message says why (the server's own words
    when it answered)."""


@dataclass(frozen=True)
class Credential:
    control_url: str
    worker_id: str
    worker_token: str
    path: Path
    #: ``sha256:<hex>`` the control plane's certificate must match, or None
    #: (plain http, or a credential from before #786).
    ca_fingerprint: str | None = None


def normalize_url(url: str) -> str:
    """``HTTP://Box:8000/`` -> ``http://box:8000``: what two spellings of
    one control plane have in common. The default port is made explicit."""
    parts = urlsplit(url.strip())
    scheme = parts.scheme.lower()
    if scheme not in ("http", "https") or not parts.hostname:
        raise ValueError(f"control URL must be http(s)://host:port, got "
                         f"{url!r}")
    port = parts.port or (443 if scheme == "https" else 80)
    host = parts.hostname.lower()
    netloc = f"[{host}]:{port}" if ":" in host else f"{host}:{port}"
    return urlunsplit((scheme, netloc, parts.path.rstrip("/"), "", ""))


def credential_dir(user_data: Path) -> Path:
    return user_data / CREDENTIAL_DIR_NAME


def credential_path(user_data: Path, control_url: str) -> Path:
    """``<user-data>/agent/<host>-<port>.token``."""
    parts = urlsplit(normalize_url(control_url))
    host = re.sub(r"[^a-z0-9.-]+", "_", (parts.hostname or "").lower())
    return credential_dir(user_data) / f"{host}-{parts.port}.token"


def load_credential(user_data: Path, control_url: str) -> Credential | None:
    """The stored credential for *control_url*, or None (a file for another
    URL that maps to the same name, or one that cannot be read, is None)."""
    path = credential_path(user_data, control_url)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        stored_url = str(data["control_url"])
        worker_id = str(data["worker_id"])
        token = str(data["worker_token"])
        raw_pin = data.get("ca_fingerprint")
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return None
    try:
        if normalize_url(stored_url) != normalize_url(control_url):
            return None
    except ValueError:
        return None
    return Credential(stored_url, worker_id, token, path,
                      _stored_pin(raw_pin, path))


def _stored_pin(raw: Any, path: Path) -> str | None:
    """The recorded pin, or None. A malformed one is logged and ignored:
    the credential (the worker token) stays usable."""
    if not raw:
        return None
    try:
        return fp.normalize(str(raw))
    except ValueError:
        logger.error("ignoring the malformed ca_fingerprint %r in %s; pass "
                     "--ca-fingerprint again to pin the certificate", raw,
                     path)
        return None


def save_credential(user_data: Path, control_url: str, worker_id: str,
                    worker_token: str, *,
                    ca_fingerprint: str | None = None) -> Path:
    """Write the credential, readable by this OS user only."""
    path = credential_path(user_data, control_url)
    path.parent.mkdir(parents=True, exist_ok=True)
    if sys.platform != "win32":
        os.chmod(path.parent, 0o700)
    data = {"control_url": normalize_url(control_url),
            "worker_id": worker_id, "worker_token": worker_token}
    if ca_fingerprint:
        data["ca_fingerprint"] = fp.normalize(ca_fingerprint)
    body = json.dumps(data, indent=2)
    tmp = path.with_suffix(".tmp")
    fd = os.open(str(tmp), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        os.write(fd, body.encode("utf-8"))
    finally:
        os.close(fd)
    if sys.platform != "win32":
        os.chmod(tmp, 0o600)
    os.replace(tmp, path)
    return path


def record_fingerprint(user_data: Path, control_url: str,
                       fingerprint: str) -> Path | None:
    """Store the pin *fingerprint* (given with ``--ca-fingerprint``) in the
    credential for *control_url*. None when there is no credential to store
    it in or it is stored already (no write)."""
    stored = load_credential(user_data, control_url)
    if stored is None or stored.ca_fingerprint == fp.normalize(fingerprint):
        return None
    return save_credential(user_data, control_url, stored.worker_id,
                           stored.worker_token, ca_fingerprint=fingerprint)


def forget_credential(user_data: Path, control_url: str) -> Path | None:
    """Delete the credential for *control_url*. Returns its path, or None
    when there was none. A file at that path whose stored URL is another
    control plane's (the same host and port under another path) is left
    alone; one that cannot be read is deleted (nothing could use it)."""
    path = credential_path(user_data, control_url)
    if not path.exists():
        return None
    try:
        stored_url = str(json.loads(path.read_text(encoding="utf-8"))
                         ["control_url"])
        other = normalize_url(stored_url) != normalize_url(control_url)
    except (OSError, ValueError, KeyError, TypeError):
        other = False
    if other:
        return None
    path.unlink()
    return path


class _UnixConnection(http.client.HTTPConnection):
    """``http.client`` over a Unix-domain socket at *path*."""

    def __init__(self, path: str, host: str, **kwargs: Any) -> None:
        super().__init__(host, **kwargs)
        self._uds_path = path

    def connect(self) -> None:
        sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        try:
            sock.settimeout(self.timeout)
            sock.connect(self._uds_path)
        except OSError:
            sock.close()
            raise
        self.sock = sock


class UnixHTTPHandler(urllib.request.HTTPHandler):
    """``urllib`` handler that sends every ``http`` request to the Unix
    socket at *path* (an SSH worker's tunnel, #784)."""

    def __init__(self, path: str) -> None:
        super().__init__()
        self.path = path

    def http_open(self, req: urllib.request.Request) -> Any:
        return self.do_open(
            lambda host, **kwargs: _UnixConnection(self.path, host, **kwargs),
            req)


def enroll(control_url: str, token: str, *, name: str,
           platform: dict[str, str], devices: list[dict[str, Any]],
           mounts: dict[str, str] | None = None,
           timeout: float = ENROLL_TIMEOUT_S,
           trust: ControlPlaneTrust | None = None,
           uds: str | None = None) -> tuple[str, str]:
    """``POST /api/workers/enroll``. Returns ``(worker_id, worker_token)``.

    Over ``https`` the request goes through *trust*'s context (the same
    verifier the worker socket uses). With *uds* it goes to that Unix
    socket (``http`` only)."""
    url = normalize_url(control_url) + "/api/workers/enroll"
    body = json.dumps({"token": token.strip(), "name": name,
                       "platform": platform, "devices": devices,
                       "mounts": mounts or {}}).encode("utf-8")
    request = urllib.request.Request(
        url, data=body, method="POST",
        headers={"Content-Type": "application/json"})
    handlers: list[Any] = []
    if uds:
        handlers.append(UnixHTTPHandler(uds))
    elif url.startswith("https:"):
        trust = trust or ControlPlaneTrust()
        handlers.append(urllib.request.HTTPSHandler(context=trust.context()))
    opener = urllib.request.build_opener(*handlers)
    try:
        with opener.open(request, timeout=timeout) as response:
            answer = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raise EnrollError(_detail(exc)) from exc
    except (urllib.error.URLError, OSError) as exc:
        reason = getattr(exc, "reason", exc)
        if isinstance(reason, TrustError):
            raise EnrollError(str(reason)) from exc
        if isinstance(reason, ssl.SSLCertVerificationError):
            raise EnrollError(untrusted_message(
                normalize_url(control_url), reason)) from exc
        raise EnrollError(f"could not reach {control_url}: {reason}") from exc
    except ValueError as exc:
        raise EnrollError(f"{control_url} answered with something that is "
                          "not JSON; is it a CodefyUI server?") from exc
    try:
        return str(answer["worker_id"]), str(answer["worker_token"])
    except (KeyError, TypeError) as exc:
        raise EnrollError(f"{control_url} answered without a worker "
                          "token") from exc


def _detail(exc: urllib.error.HTTPError) -> str:
    try:
        detail = json.loads(exc.read().decode("utf-8")).get("detail")
    except (ValueError, AttributeError, OSError):
        detail = None
    if exc.code == 421:
        detail = ("the server does not accept this address as its Host; "
                  "start it with --host 0.0.0.0, or add the address to "
                  "CODEFYUI_EXTRA_ALLOWED_HOSTS")
    return f"HTTP {exc.code}: {detail or exc.reason}"
